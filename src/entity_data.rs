/// Définition + textures pour un MobKind (tex = chemins relatifs entity/).
pub fn def_for_kind(kind: u8) -> Option<(&'static str, &'static [&'static str], &'static EDef)> {
    KINDS.iter().find(|k| k.kind == kind).map(|k| (k.tex, textures_of(k.kind), &k.def))
}

/// Toutes les textures (entity/…) utilisées par un kind, dans l'ordre des index `tex`.
